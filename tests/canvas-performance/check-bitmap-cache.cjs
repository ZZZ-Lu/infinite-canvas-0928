const fs = require('node:fs'), vm = require('node:vm'), ts = require('typescript'), assert = require('node:assert/strict');
const code = ts.transpileModule(fs.readFileSync('src/utils/promptSurfaceCache.ts', 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const context = { exports:{}, document:{createElement:()=>({width:0,height:0,getContext:()=>({drawImage(){}})})} };
vm.runInNewContext(code,context);
const {cacheSurfaceBitmap:put,getSurfaceBitmap:get}=context.exports;
const source={width:1024,height:1024};
for(let i=0;i<8;i++)put(String(i),source);
const retained=get('0'); assert.ok(retained);
put('8',source); assert.equal(get('1'),undefined); assert.equal(get('0'),retained);
put('oversized',{width:5000,height:5000}); assert.equal(get('oversized'),undefined);
put('latest',{width:100,height:100}); assert.equal(get('latest').width,100);
let events=0;
context.window={dispatchEvent:()=>events++}; context.Event=class {constructor(type){this.type=type;}};
const {getCardSurfaceRevision:revision,publishCardSurface:publish,getCardSurface:read}=context.exports;
const card={prompt:'first',ratio:'1:1',res:'2K',referenceImages:[{url:'ref'}]};
const light=revision(card,false),dark=revision(card,true);
assert.notEqual(light,dark);
const changed=revision({...card,prompt:'changed'},false);
assert.notEqual(light,changed);
assert.notEqual(light,revision({...card,referenceImages:[{url:'new-ref'}]},false));
publish('card','panel',light,'latest');
assert.equal(read('card','panel',light),get('latest'));
assert.equal(read('card','panel',dark),undefined);
assert.equal(read('card','panel',changed),undefined);
publish('card','panel',light,'latest'); assert.equal(events,1);
publish('missing','panel',light,'absent'); assert.equal(read('missing','panel',light),undefined);
// Aliases must not pin evicted canvas objects or copy surfaces outside the budget.
for(let i=0;i<12;i++)put('evict-'+i,source);
assert.equal(read('card','panel',light),undefined);
console.log('PASS: bitmap budget/LRU, shared surface identity, content/theme invalidation, deduplicated repaint, eviction-safe aliases');
